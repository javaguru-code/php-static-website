<p>Symbols can be written directly with Unicode or via HTML entities. Prefer direct characters in UTF‑8; use entities when necessary for readability or safety.</p>

<h2>Examples</h2>
<ul>
  <li>Currency: <code>$ € £ ¥</code></li>
  <li>Math: <code>&amp;times; (×)</code>, <code>&amp;plusmn; (±)</code></li>
  <li>Arrows: <code>&amp;rarr; (→)</code>, <code>&amp;uarr; (↑)</code></li>
  <li>Misc: <code>&amp;copy; (©)</code>, <code>&amp;reg; (®)</code>, <code>&amp;trade; (™)</code></li>
</ul>

