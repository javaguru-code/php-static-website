<p>Meta tags provide metadata about the page for browsers, search engines, and social platforms. They live in the <code>&lt;head&gt;</code>.</p>

<h2>Essential</h2>
<pre><code class="language-html">&lt;meta charset="utf-8"&gt;
&lt;meta name="viewport" content="width=device-width, initial-scale=1"&gt;
&lt;meta name="description" content="Concise page summary"&gt;
</code></pre>

<h2>Robots and indexing</h2>
<pre><code class="language-html">&lt;meta name="robots" content="index,follow"&gt;
</code></pre>

<h2>Social sharing (Open Graph/Twitter)</h2>
<pre><code class="language-html">&lt;meta property="og:title" content="Page Title"&gt;
&lt;meta property="og:description" content="Summary"&gt;
&lt;meta property="og:image" content="https://example.com/cover.jpg"&gt;
&lt;meta name="twitter:card" content="summary_large_image"&gt;
</code></pre>
