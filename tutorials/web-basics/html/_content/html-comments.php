<p>Comments help you annotate HTML without affecting rendering. Use them for explanations or temporary disabling of markup, but don’t store secrets or critical info in comments.</p>

<h2>Syntax</h2>
<pre><code class="language-html">&lt;!-- This is a comment --&gt;
&lt;!--
  Multi‑line comments
  are fine too.
--&gt;
</code></pre>

<p>Note: Old IE conditional comments are obsolete; modern browsers ignore them.</p>
