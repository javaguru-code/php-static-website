<p>Any plain‑text editor works for HTML, but a code‑focused editor boosts speed and accuracy with syntax highlighting, Emmet, and extensions.</p>

<h2>Recommended editors</h2>
<ul>
  <li><strong>VS Code</strong> (free, extensible, great HTML/CSS/JS support)</li>
  <li>Sublime Text, WebStorm, Vim/Neovim — all solid choices depending on your workflow</li>
</ul>

<h2>VS Code setup</h2>
<ol>
  <li>Install from <a href="https://code.visualstudio.com/" target="_blank" rel="noopener">code.visualstudio.com</a>.</li>
  <li>Extensions: Live Server, Prettier, ESLint, HTML CSS Support, IntelliSense for CSS class names.</li>
  <li>Settings: enable <code>formatOnSave</code>, set tab size (2 spaces), and choose a readable font.</li>
</ol>

<h2>Working efficiently</h2>
<ul>
  <li><strong>Emmet</strong>: type <code>ul>li*3</code> then press tab to expand into a list.</li>
  <li><strong>Live Server</strong>: auto‑reload the browser on save while you edit HTML/CSS.</li>
  <li><strong>Prettier</strong>: keep formatting consistent across the project.</li>
</ul>
