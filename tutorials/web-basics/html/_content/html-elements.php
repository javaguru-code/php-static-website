<p>Elements are the building blocks formed by tags plus their content. Elements nest to create a document tree (DOM) that browsers render and scripts can manipulate.</p>

<h2>Hierarchy</h2>
<ul>
  <li>Parent/child relationships come from nesting</li>
  <li>Siblings share the same parent</li>
  <li>Keep nesting logical for semantics and accessibility</li>
</ul>

<h2>Example</h2>
<pre><code class="language-html">&lt;main&gt;
  &lt;article&gt;
    &lt;h1&gt;Title&lt;/h1&gt;
    &lt;p&gt;Intro text&lt;/p&gt;
  &lt;/article&gt;
&lt;/main&gt;
</code></pre>
