<p>Use semantic elements and clean HTML to help search engines and assistive tech. Good structure improves understanding and ranking.</p>

<h2>Practices</h2>
<ul>
  <li>Use proper headings (one main topic in <code>&lt;h1&gt;</code>, logical hierarchy)</li>
  <li>Descriptive link text and <code>alt</code> for images</li>
  <li>Use <code>&lt;main&gt;</code>, <code>&lt;nav&gt;</code>, <code>&lt;article&gt;</code>, <code>&lt;section&gt;</code>, <code>&lt;aside&gt;</code>, <code>&lt;footer&gt;</code></li>
  <li>Breadcrumbs and clear navigation</li>
</ul>

<h2>Structured data</h2>
<p>Enhance with JSON‑LD schema in the head when needed; keep HTML readable regardless.</p>
