<p>Ordered lists (<code>&lt;ol&gt;</code>) number items. You can control numbering and direction.</p>
<ul>
  <li><code>start</code>: set the initial number</li>
  <li><code>reversed</code>: countdown order</li>
  <li><code>type</code>: 1, a, A, i, I (presentation is usually handled by CSS)</li>
</ul>
