<p><code>&lt;p&gt;</code> elements define paragraphs. Browsers collapse whitespace inside paragraphs; use CSS for spacing, not extra <code>&lt;br&gt;</code> lines.</p>

<h2>Tips</h2>
<ul>
  <li>Do not nest block elements inside <code>&lt;p&gt;</code></li>
  <li>Use <code>&lt;br&gt;</code> for a line break within the same paragraph</li>
  <li>Use <code>&lt;pre&gt;</code> for preformatted text where whitespace matters</li>
</ul>

<h2>Example</h2>
<pre><code class="language-html">&lt;p&gt;First paragraph.&lt;/p&gt;
&lt;p&gt;Second paragraph with a&lt;br&gt;manual line break.&lt;/p&gt;
</code></pre>
