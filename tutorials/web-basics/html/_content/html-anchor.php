<p>Anchors (<code>&lt;a&gt;</code>) create hyperlinks. Use clear, descriptive link text and valid destinations.</p>

<h2>Key attributes</h2>
<ul>
  <li><code>href</code>: URL, fragment (<code>#id</code>), <code>mailto:</code>, or <code>tel:</code></li>
  <li><code>target="_blank"</code> with <code>rel="noopener noreferrer"</code> for security</li>
  <li><code>download</code>: suggest saving a resource</li>
</ul>

<h2>Examples</h2>
<pre><code class="language-html">&lt;a href="/contact"&gt;Contact us&lt;/a&gt;
&lt;a href="#faq"&gt;Jump to FAQ&lt;/a&gt;
&lt;a href="mailto:info@example.com"&gt;Email us&lt;/a&gt;
</code></pre>
