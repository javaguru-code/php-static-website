<p>URLs can contain only a subset of characters. URL encoding (percent‑encoding) represents unsafe characters with <code>%</code> followed by hex codes.</p>

<h2>When it applies</h2>
<ul>
  <li>In <code>href</code> and <code>src</code> URLs</li>
  <li>In query strings and form submissions</li>
</ul>

