<p>Use semantic containers to structure pages. Semantics describe meaning; CSS handles visual layout.</p>

<h2>Common sections</h2>
<ul>
  <li><code>&lt;header&gt;</code> site or section header</li>
  <li><code>&lt;nav&gt;</code> main navigation</li>
  <li><code>&lt;main&gt;</code> primary content (one per page)</li>
  <li><code>&lt;section&gt;</code> thematic grouping, <code>&lt;article&gt;</code> self‑contained content</li>
  <li><code>&lt;aside&gt;</code> complementary info, <code>&lt;footer&gt;</code> footer</li>
</ul>

<h2>Example structure</h2>
<pre><code class="language-html">&lt;header&gt;...&lt;/header&gt;
&lt;main&gt;
  &lt;article&gt;...&lt;/article&gt;
  &lt;aside&gt;Sidebar&lt;/aside&gt;
&lt;/main&gt;
&lt;footer&gt;...&lt;/footer&gt;
</code></pre>
