<p>HTML (HyperText Markup Language) is the standard way to describe the structure of a web page. It isn’t a programming language — it’s a markup system made of elements and attributes that tell the browser what each piece of content means and how it fits together.</p>

<h2>Why HTML matters</h2>
<ul>
  <li>Foundation of the web: every site you visit starts as HTML.</li>
  <li>Separation of concerns: HTML handles structure; CSS handles presentation; JavaScript handles behavior.</li>
  <li>Modern HTML5 adds first‑class support for audio, video, graphics (Canvas/SVG), forms, and semantic elements.</li>
</ul>

<h2>A minimal HTML document</h2>
<pre><code class="language-html">&lt;!DOCTYPE html&gt;
&lt;html lang="en"&gt;
  &lt;head&gt;
    &lt;meta charset="utf-8" /&gt;
    &lt;meta name="viewport" content="width=device-width, initial-scale=1" /&gt;
    &lt;title&gt;My first page&lt;/title&gt;
  &lt;/head&gt;
  &lt;body&gt;
    &lt;h1&gt;Hello, HTML!&lt;/h1&gt;
    &lt;p&gt;This is a paragraph of text.&lt;/p&gt;
  &lt;/body&gt;
&lt;/html&gt;
</code></pre>

<h2>Core building blocks</h2>
<ul>
  <li><strong>Tags</strong>: Keywords in angle brackets, e.g., <code>&lt;p&gt;</code>, <code>&lt;a&gt;</code>, <code>&lt;img&gt;</code>.</li>
  <li><strong>Elements</strong>: A tag pair plus its content, e.g., <code>&lt;p&gt;Hello&lt;/p&gt;</code>.</li>
  <li><strong>Attributes</strong>: Extra information on the start tag, e.g., <code>&lt;a href="/"&gt;</code>.</li>
  <li><strong>Semantics</strong>: Meaningful tags like <code>&lt;header&gt;</code>, <code>&lt;main&gt;</code>, <code>&lt;article&gt;</code> improve accessibility and SEO.</li>
  <li><strong>Document structure</strong>: <code>&lt;!DOCTYPE&gt;</code>, <code>&lt;html&gt;</code>, <code>&lt;head&gt;</code>, and <code>&lt;body&gt;</code> form the skeleton.</li>
</ul>

