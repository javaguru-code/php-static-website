<p>The character encoding tells the browser how to interpret bytes as characters. Use UTF‑8 to support virtually all languages and symbols.</p>

<h2>Set the charset</h2>
<pre><code class="language-html">&lt;meta charset="utf-8"&gt;
</code></pre>

<ul>
  <li>Place it early in <code>&lt;head&gt;</code></li>
  <li>Ensure your files are saved as UTF‑8 without BOM</li>
  <li>Avoid mixing encodings across resources</li>
</ul>
