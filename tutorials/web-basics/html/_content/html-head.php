<p>The <code>&lt;head&gt;</code> contains metadata about the document that isn’t displayed directly. It defines the title, character encoding, viewport, linked styles, scripts, and social/SEO tags.</p>

<h2>Common head tags</h2>
<pre><code class="language-html">&lt;meta charset="utf-8"&gt;
&lt;meta name="viewport" content="width=device-width, initial-scale=1"&gt;
&lt;title&gt;Page title&lt;/title&gt;
&lt;meta name="description" content="Short summary for search results"&gt;
&lt;link rel="stylesheet" href="/css/app.css"&gt;
&lt;script src="/js/app.js" defer&gt;&lt;/script&gt;
</code></pre>

<p>Optional: <code>&lt;base&gt;</code>, <code>theme-color</code>, Open Graph/Twitter tags for sharing.</p>
