<p>Headings from <code>&lt;h1&gt;</code> to <code>&lt;h6&gt;</code> create a visual and semantic outline. Use them to structure content by importance.</p>

<h2>Guidelines</h2>
<ul>
  <li><code>&lt;h1&gt;</code> represents the page’s main topic</li>
  <li>Follow a logical hierarchy (don’t skip levels for styling)</li>
  <li>Good for SEO and screen readers: headings act as landmarks</li>
</ul>

<h2>Example</h2>
<pre><code class="language-html">&lt;h1&gt;Cooking Basics&lt;/h1&gt;
&lt;h2&gt;Tools&lt;/h2&gt;
&lt;h3&gt;Knives&lt;/h3&gt;
</code></pre>
