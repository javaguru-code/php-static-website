<p>HTML supports three list types: unordered (<code>&lt;ul&gt;</code>), ordered (<code>&lt;ol&gt;</code>), and description lists (<code>&lt;dl&gt;</code>).</p>
<ul>
  <li>Use <code>&lt;ul&gt;</code> for items with no inherent order</li>
  <li>Use <code>&lt;ol&gt;</code> when order matters (steps, rankings)</li>
  <li>Use <code>&lt;dl&gt;</code> for term–description pairs</li>
</ul>
