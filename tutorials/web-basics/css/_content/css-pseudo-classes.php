<p>Pseudo-classes style elements in a particular state: hover, focus, checked, disabled, etc.</p>

<h2>Examples</h2>
<pre><code class="language-css">a:hover { text-decoration: underline; }
input:focus { outline: 2px solid #0d6efd; outline-offset: 2px; }
li:nth-child(odd) { background: #f8f9fa; }
</code></pre>
