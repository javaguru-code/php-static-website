<p>Shorthand properties set multiple related values at once. Use them carefully to avoid unintended overrides.</p>

<h2>Examples</h2>
<pre><code class="language-css">/***** Longhand *****/
.box { margin-top: 1rem; margin-right: .5rem; margin-bottom: 1rem; margin-left: .5rem; }
/***** Shorthand (TRBL) *****/
.box { margin: 1rem .5rem; }

/***** Border *****/
.box { border: 1px solid #dee2e6; }
</code></pre>
