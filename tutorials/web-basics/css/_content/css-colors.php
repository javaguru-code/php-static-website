<p>CSS supports many color formats: keywords, hex, rgb()/rgba(), hsl()/hsla(), and modern <code>oklch()</code>/<code>color()</code> in supporting browsers.</p>

<h2>Examples</h2>
<pre><code class="language-css">.brand { color: #0d6efd; }
.alert { background: hsl(0 100% 95%); color: hsl(0 60% 40%); }
.badge { background: rgb(25 135 84 / 0.15); }
</code></pre>
