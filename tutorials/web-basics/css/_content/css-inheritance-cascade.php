<p>The cascade resolves conflicts using origin, importance, specificity, and order. Some properties inherit from parents (like <code>color</code>), others don’t (like <code>margin</code>).</p>

<h2>Tips</h2>
<ul>
  <li>Prefer low-specificity class selectors</li>
  <li>Use custom properties for design tokens</li>
  <li>Avoid <code>!important</code> unless in scoped utilities</li>
</ul>
