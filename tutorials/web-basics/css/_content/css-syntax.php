<p>CSS rules are made of a selector and one or more declarations (property: value) inside braces.</p>

<h2>Rule structure</h2>
<pre><code class="language-css">/* selector */
.card p.highlight {
  /* declarations */
  color: #333;
  margin: 1rem 0;
}
</code></pre>

<h2>Comments and whitespace</h2>
<pre><code class="language-css">/* This is a comment */
.nav { display: flex; }
</code></pre>
