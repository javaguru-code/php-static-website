<p>Positioning lets you offset elements from their normal flow: <code>static</code>, <code>relative</code>, <code>absolute</code>, <code>fixed</code>, and <code>sticky</code>.</p>

<h2>Examples</h2>
<pre><code class="language-css">.badge { position: absolute; top: .5rem; right: .5rem; }
.header { position: sticky; top: 0; z-index: 10; }
.modal { position: fixed; inset: 0; }
</code></pre>
